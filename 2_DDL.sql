-- ---------------------------------------------------------------------
-- TIPO_TEMPORADA (entidad agregada): ALTA, MEDIA, BAJA.
-- ---------------------------------------------------------------------
CREATE TABLE tipo_temporada (
  id_tipo_temporada NUMBER(2)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre            VARCHAR2(10 CHAR)  NOT NULL,
  CONSTRAINT pk_tipo_temporada        PRIMARY KEY (id_tipo_temporada),
  CONSTRAINT uk_tipo_temporada_nombre UNIQUE (nombre),
  CONSTRAINT ck_tipo_temporada_nombre CHECK (nombre IN ('ALTA', 'MEDIA', 'BAJA'))
);

COMMENT ON TABLE tipo_temporada IS 'Categoría de temporada (entidad agregada). Permite agrupar ingresos por tipo en ROLLUP/CUBE.';


-- ---------------------------------------------------------------------
-- TEMPORADA: Registra una temporada concreta en un año (ej. "SEMANA SANTA 2026"), con fechas reales de inicio y fin.
-- Las temporadas no pueden cruzarse entre sí ni dejar días sin cubrir.
-- fecha_fin es inclusiva: incluye la última noche de la temporada.
-- ---------------------------------------------------------------------
CREATE TABLE temporada (
  id_temporada      NUMBER(5)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_tipo_temporada NUMBER(2)          NOT NULL,
  nombre            VARCHAR2(60 CHAR)  NOT NULL,
  anio              NUMBER(4)          NOT NULL,
  fecha_inicio      DATE               NOT NULL,
  fecha_fin         DATE               NOT NULL,
  CONSTRAINT pk_temporada            PRIMARY KEY (id_temporada),
  CONSTRAINT fk_temporada_tipo       FOREIGN KEY (id_tipo_temporada) REFERENCES tipo_temporada (id_tipo_temporada),
  CONSTRAINT uk_temporada_nombre     UNIQUE (nombre),
  CONSTRAINT uk_temporada_inicio     UNIQUE (fecha_inicio),
  CONSTRAINT ck_temporada_rango      CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT ck_temporada_sin_hora   CHECK (fecha_inicio = TRUNC(fecha_inicio) AND fecha_fin = TRUNC(fecha_fin)),
  -- El año de la temporada es el de su fecha de inicio (la de diciembre-enero pertenece al año en que empieza).
  CONSTRAINT ck_temporada_anio       CHECK (anio = EXTRACT(YEAR FROM fecha_inicio))
);

COMMENT ON TABLE  temporada              IS 'Temporadas por año con fechas reales. Sin solapes ni huecos (RN7).';
COMMENT ON COLUMN temporada.anio         IS 'Año de la temporada, igual al año de fecha_inicio.';
COMMENT ON COLUMN temporada.fecha_fin    IS 'Última noche (inclusiva) que pertenece a la temporada.';


-- ---------------------------------------------------------------------
-- TARIFA: Valor por noche de una habitación en una temporada específica.
-- ---------------------------------------------------------------------
CREATE TABLE tarifa (
  id_tarifa     NUMBER(8)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_habitacion NUMBER(8)     NOT NULL,
  id_temporada  NUMBER(5)     NOT NULL,
  valor_noche   NUMBER(12,2)  NOT NULL,
  CONSTRAINT pk_tarifa            PRIMARY KEY (id_tarifa),
  CONSTRAINT fk_tarifa_habitacion FOREIGN KEY (id_habitacion) REFERENCES habitacion (id_habitacion),
  CONSTRAINT fk_tarifa_temporada  FOREIGN KEY (id_temporada)  REFERENCES temporada (id_temporada),
  -- Una sola tarifa por habitación y temporada.
  CONSTRAINT uk_tarifa_hab_temp   UNIQUE (id_habitacion, id_temporada),
  CONSTRAINT ck_tarifa_valor      CHECK (valor_noche > 0)
);

COMMENT ON TABLE  tarifa             IS 'Valor por noche de cada habitación en cada temporada.';
COMMENT ON COLUMN tarifa.valor_noche IS 'Valor vigente por noche en pesos colombianos. Sus cambios se auditan en AUDITORIA_TARIFA.';


-- ---------------------------------------------------------------------
-- AUDITORIA_TARIFA: Registra quién y cuándo modificó un precio, indicando el valor anterior y el nuevo.
-- id_tarifa no es clave foránea para garantizar que el historial se conserve aunque la tarifa sea eliminada.
-- ---------------------------------------------------------------------
CREATE TABLE auditoria_tarifa (
  id_auditoria   NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_tarifa      NUMBER(8)      NOT NULL,
  operacion      VARCHAR2(6)    NOT NULL,
  valor_anterior NUMBER(12,2),
  valor_nuevo    NUMBER(12,2),
  usuario_bd     VARCHAR2(128)  DEFAULT USER NOT NULL,
  fecha_cambio   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_auditoria_tarifa    PRIMARY KEY (id_auditoria),
  CONSTRAINT ck_auditoria_operacion CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
  -- Coherencia entre la operación y los valores registrados:
  -- INSERT solo tiene valor nuevo, DELETE solo valor anterior, UPDATE ambos.
  CONSTRAINT ck_auditoria_valores   CHECK (
       (operacion = 'INSERT' AND valor_anterior IS NULL     AND valor_nuevo IS NOT NULL)
    OR (operacion = 'DELETE' AND valor_anterior IS NOT NULL AND valor_nuevo IS NULL)
    OR (operacion = 'UPDATE' AND valor_anterior IS NOT NULL AND valor_nuevo IS NOT NULL)
  )
);

COMMENT ON TABLE  auditoria_tarifa            IS 'Historial de cambios sobre TARIFA (entidad agregada, Entrega 2). Sin FK a TARIFA a propósito.';
COMMENT ON COLUMN auditoria_tarifa.id_tarifa  IS 'Tarifa afectada. Relación lógica sin FK física para conservar la auditoría si la tarifa se borra.';
COMMENT ON COLUMN auditoria_tarifa.usuario_bd IS 'Usuario de Oracle que hizo el cambio (USER).';


/* =====================================================================
   3. CLIENTES Y RESERVAS
