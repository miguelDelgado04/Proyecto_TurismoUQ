-- ---------------------------------------------------------------------
-- LIQUIDACION_MENSUAL:
-- Cierre de cuentas de un alojamiento en un mes específico.
-- Impide liquidar dos veces el mismo alojamiento en el mismo mes.

-- ---------------------------------------------------------------------
CREATE TABLE liquidacion_mensual (
  id_liquidacion   NUMBER(8)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_alojamiento   NUMBER(6)     NOT NULL,
  anio             NUMBER(4)     NOT NULL,
  mes              NUMBER(2)     NOT NULL,
  noches_vendidas  NUMBER(6)     DEFAULT 0 NOT NULL,
  total_estadias   NUMBER(14,2)  DEFAULT 0 NOT NULL,
  total_servicios  NUMBER(14,2)  DEFAULT 0 NOT NULL,
  total_reembolsos NUMBER(14,2)  DEFAULT 0 NOT NULL,
  total_neto       NUMBER(14,2)  DEFAULT 0 NOT NULL,
  fecha_generacion DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_liquidacion_mensual PRIMARY KEY (id_liquidacion),
  CONSTRAINT fk_liquidacion_aloj    FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uk_liquidacion_periodo UNIQUE (id_alojamiento, anio, mes),
  CONSTRAINT ck_liquidacion_anio    CHECK (anio >= 2024),
  CONSTRAINT ck_liquidacion_mes     CHECK (mes BETWEEN 1 AND 12),
  CONSTRAINT ck_liquidacion_no_neg  CHECK (noches_vendidas >= 0 AND total_estadias >= 0
                                           AND total_servicios >= 0 AND total_reembolsos >= 0),
  CONSTRAINT ck_liquidacion_cuadre  CHECK (total_neto = total_estadias + total_servicios - total_reembolsos)
);

COMMENT ON TABLE  liquidacion_mensual                  IS 'Liquidación mensual por alojamiento generada por el cursor de la Entrega 2 (entidad agregada).';
COMMENT ON COLUMN liquidacion_mensual.total_estadias   IS 'Suma de valor_noche de las noches del mes en reservas CONFIRMADA o COMPLETADA (RN11).';
COMMENT ON COLUMN liquidacion_mensual.total_reembolsos IS 'Suma de monto_reembolso de las cancelaciones del mes.';
COMMENT ON COLUMN liquidacion_mensual.total_neto       IS 'total_estadias + total_servicios - total_reembolsos.';


/* =====================================================================
   5. VERIFICACIÓN
-- Resumen final de la estructura creada (tablas, claves primarias, foráneas y restricciones).
   ===================================================================== */
SELECT table_name,
       SUM(CASE WHEN constraint_type = 'P' THEN 1 ELSE 0 END) AS pk,
       SUM(CASE WHEN constraint_type = 'R' THEN 1 ELSE 0 END) AS fk,
       SUM(CASE WHEN constraint_type = 'U' THEN 1 ELSE 0 END) AS uk,
       SUM(CASE WHEN constraint_type = 'C' AND constraint_name NOT LIKE 'SYS%' THEN 1 ELSE 0 END) AS ck,
       SUM(CASE WHEN constraint_type = 'C' AND constraint_name LIKE 'SYS%'     THEN 1 ELSE 0 END) AS not_null
FROM   user_constraints
WHERE  table_name IN (
         'MUNICIPIO', 'TIPO_ALOJAMIENTO', 'ROL', 'USUARIO_SISTEMA', 'ALOJAMIENTO',
         'HABITACION', 'SERVICIO', 'TIPO_TEMPORADA', 'TEMPORADA', 'TARIFA',
         'AUDITORIA_TARIFA', 'CLIENTE', 'RESERVA', 'RESERVA_HABITACION',
         'RESERVA_NOCHE', 'PAGO', 'CANCELACION', 'RESERVA_SERVICIO', 'RESENA',
         'LIQUIDACION_MENSUAL')
GROUP  BY table_name
ORDER  BY table_name;

