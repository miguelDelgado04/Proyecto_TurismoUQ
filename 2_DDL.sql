-- ---------------------------------------------------------------------
-- CLIENTE:
-- El número de documento es único por cada tipo de documento.
-- ---------------------------------------------------------------------
CREATE TABLE cliente (
  id_cliente     NUMBER(8)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
  tipo_documento VARCHAR2(3)         NOT NULL,
  num_documento  VARCHAR2(20)        NOT NULL,
  nombres        VARCHAR2(80 CHAR)   NOT NULL,
  apellidos      VARCHAR2(80 CHAR)   NOT NULL,
  correo         VARCHAR2(120 CHAR)  NOT NULL,
  telefono       VARCHAR2(20)        NOT NULL,
  ciudad_origen  VARCHAR2(80 CHAR)   NOT NULL,
  fecha_registro DATE                DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_cliente            PRIMARY KEY (id_cliente),
  CONSTRAINT uk_cliente_documento  UNIQUE (tipo_documento, num_documento),
  CONSTRAINT uk_cliente_correo     UNIQUE (correo),
  CONSTRAINT ck_cliente_tipo_doc   CHECK (tipo_documento IN ('CC', 'CE', 'TI', 'PA', 'PPT')),
  CONSTRAINT ck_cliente_num_doc    CHECK (REGEXP_LIKE(num_documento, '^[A-Za-z0-9]{4,20}$')),
  CONSTRAINT ck_cliente_telefono   CHECK (REGEXP_LIKE(telefono, '^\+?[0-9 ]{7,15}$')),
  CONSTRAINT ck_cliente_correo     CHECK (REGEXP_LIKE(correo, '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'))
);

COMMENT ON TABLE  cliente                IS 'Turistas que reservan en la plataforma.';
COMMENT ON COLUMN cliente.tipo_documento IS 'CC cédula, CE cédula de extranjería, TI tarjeta de identidad, PA pasaporte, PPT permiso por protección temporal.';
COMMENT ON COLUMN cliente.ciudad_origen  IS 'Ciudad de procedencia del cliente (texto libre).';


-- ---------------------------------------------------------------------
-- RESERVA (cabecera):
-- Registra los datos generales de un grupo de reserva.
-- Toda la reserva debe pertenecer a un solo alojamiento.
-- fecha_checkin y fecha_checkout definen el rango de fechas general de la estadía.
-- ---------------------------------------------------------------------
CREATE TABLE reserva (
  id_reserva     NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_cliente     NUMBER(8)     NOT NULL,
  id_alojamiento NUMBER(6)     NOT NULL,
  fecha_reserva  DATE          DEFAULT SYSDATE NOT NULL,
  fecha_checkin  DATE          NOT NULL,
  fecha_checkout DATE          NOT NULL,
  estado         VARCHAR2(10)  DEFAULT 'PENDIENTE' NOT NULL,
  CONSTRAINT pk_reserva              PRIMARY KEY (id_reserva),
  CONSTRAINT fk_reserva_cliente      FOREIGN KEY (id_cliente)     REFERENCES cliente (id_cliente),
  CONSTRAINT fk_reserva_alojamiento  FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT ck_reserva_estado       CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA', 'COMPLETADA')),
  -- Mínimo una noche.
  CONSTRAINT ck_reserva_fechas       CHECK (fecha_checkout > fecha_checkin),
  CONSTRAINT ck_reserva_sin_hora     CHECK (fecha_checkin = TRUNC(fecha_checkin) AND fecha_checkout = TRUNC(fecha_checkout)),
  -- La reserva se hace antes o el mismo día de la llegada.
  CONSTRAINT ck_reserva_anticipacion CHECK (TRUNC(fecha_reserva) <= fecha_checkin)
);

COMMENT ON TABLE  reserva                IS 'Cabecera de la reserva: cliente, alojamiento, estado y rango general de fechas.';
COMMENT ON COLUMN reserva.id_alojamiento IS 'Alojamiento de la reserva. Todas sus habitaciones y servicios deben pertenecer a él (RN4).';
COMMENT ON COLUMN reserva.fecha_checkin  IS 'Fecha de llegada general: la menor de sus líneas (RN5).';
COMMENT ON COLUMN reserva.fecha_checkout IS 'Fecha de salida general: la mayor de sus líneas (RN5).';
COMMENT ON COLUMN reserva.estado         IS 'PENDIENTE, CONFIRMADA, CANCELADA o COMPLETADA. Transiciones válidas en RN10.';


-- ---------------------------------------------------------------------
-- RESERVA_HABITACION (línea de reserva):
-- Asigna las habitaciones reservadas y sus fechas específicas.
-- Si la reserva se borra, sus habitaciones asociadas se eliminan en cadena.
-- ---------------------------------------------------------------------
CREATE TABLE reserva_habitacion (
  id_reserva_hab NUMBER(10)  GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_reserva     NUMBER(10)  NOT NULL,
  id_habitacion  NUMBER(8)   NOT NULL,
  fecha_checkin  DATE        NOT NULL,
  fecha_checkout DATE        NOT NULL,
  num_huespedes  NUMBER(2)   NOT NULL,
  CONSTRAINT pk_reserva_habitacion  PRIMARY KEY (id_reserva_hab),
  CONSTRAINT fk_reshab_reserva      FOREIGN KEY (id_reserva)    REFERENCES reserva (id_reserva) ON DELETE CASCADE,
  CONSTRAINT fk_reshab_habitacion   FOREIGN KEY (id_habitacion) REFERENCES habitacion (id_habitacion),
  -- Una habitación aparece una sola vez en cada reserva.
  CONSTRAINT uk_reshab_reserva_hab  UNIQUE (id_reserva, id_habitacion),
  CONSTRAINT ck_reshab_fechas       CHECK (fecha_checkout > fecha_checkin),
  CONSTRAINT ck_reshab_sin_hora     CHECK (fecha_checkin = TRUNC(fecha_checkin) AND fecha_checkout = TRUNC(fecha_checkout)),
  CONSTRAINT ck_reshab_huespedes    CHECK (num_huespedes >= 1)
);

COMMENT ON TABLE  reserva_habitacion                IS 'Habitaciones de cada reserva con sus fechas propias (decisión de diseño 1).';
COMMENT ON COLUMN reserva_habitacion.fecha_checkin  IS 'Llegada de esta habitación. Rango semiabierto [checkin, checkout) para validar solapamiento (RN3).';
COMMENT ON COLUMN reserva_habitacion.fecha_checkout IS 'Salida de esta habitación. Puede coincidir con el checkin de otra reserva de la misma habitación.';
COMMENT ON COLUMN reserva_habitacion.num_huespedes  IS 'Huéspedes en la habitación. No puede superar capacidad_max (RN6).';


-- ---------------------------------------------------------------------
-- RESERVA_NOCHE:
-- Guarda el cobro de cada noche de la estadía con el valor fijado en el momento de reservar.
-- Una reserva del 20 al 26 de diciembre genera 6 noches (del 20 al 25).
-- ---------------------------------------------------------------------
CREATE TABLE reserva_noche (
  id_reserva_noche NUMBER(12)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_reserva_hab   NUMBER(10)    NOT NULL,
  fecha_noche      DATE          NOT NULL,
  id_tarifa        NUMBER(8)     NOT NULL,
  valor_noche      NUMBER(12,2)  NOT NULL,
  CONSTRAINT pk_reserva_noche       PRIMARY KEY (id_reserva_noche),
  CONSTRAINT fk_resnoche_reshab     FOREIGN KEY (id_reserva_hab) REFERENCES reserva_habitacion (id_reserva_hab) ON DELETE CASCADE,
  CONSTRAINT fk_resnoche_tarifa     FOREIGN KEY (id_tarifa)      REFERENCES tarifa (id_tarifa),
  -- Cada noche se cobra una sola vez por línea.
  CONSTRAINT uk_resnoche_reshab_fecha UNIQUE (id_reserva_hab, fecha_noche),
  CONSTRAINT ck_resnoche_sin_hora   CHECK (fecha_noche = TRUNC(fecha_noche)),
  CONSTRAINT ck_resnoche_valor      CHECK (valor_noche > 0)
);

COMMENT ON TABLE  reserva_noche             IS 'Valor de cada noche reservada con la tarifa aplicada (entidad agregada, decisión de diseño 2).';
COMMENT ON COLUMN reserva_noche.fecha_noche IS 'Fecha de la noche, desde el checkin hasta el día anterior al checkout de la línea.';
COMMENT ON COLUMN reserva_noche.id_tarifa   IS 'Tarifa de la habitación en la temporada que contiene fecha_noche.';
COMMENT ON COLUMN reserva_noche.valor_noche IS 'Valor cobrado por la noche, congelado al reservar (RN9). Base de ingresos por temporada y por mes.';


-- ---------------------------------------------------------------------
-- PAGO: Registra los abonados a una reserva.
-- Una reserva admite varios pagos parciales hasta completar el total.
-- ---------------------------------------------------------------------
CREATE TABLE pago (
  id_pago    NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_reserva NUMBER(10)    NOT NULL,
  fecha_pago DATE          DEFAULT SYSDATE NOT NULL,
  monto      NUMBER(12,2)  NOT NULL,
  metodo     VARCHAR2(16)  NOT NULL,
  estado     VARCHAR2(12)  DEFAULT 'PENDIENTE' NOT NULL,
  CONSTRAINT pk_pago         PRIMARY KEY (id_pago),
  CONSTRAINT fk_pago_reserva FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
  CONSTRAINT ck_pago_monto   CHECK (monto > 0),
  CONSTRAINT ck_pago_metodo  CHECK (metodo IN ('TARJETA_CREDITO', 'TARJETA_DEBITO', 'PSE', 'TRANSFERENCIA', 'EFECTIVO')),
  CONSTRAINT ck_pago_estado  CHECK (estado IN ('EXITOSO', 'FALLIDO', 'PENDIENTE', 'REEMBOLSADO'))
);

COMMENT ON TABLE  pago        IS 'Abonos de cada reserva. Solo los EXITOSO cuentan para el saldo (RN8).';
COMMENT ON COLUMN pago.estado IS 'EXITOSO, FALLIDO, PENDIENTE o REEMBOLSADO (pago cubierto por una cancelación con reembolso).';


-- ---------------------------------------------------------------------
-- CANCELACION:
-- Registra la cancelación de una reserva.
-- Más de 5 días de anticipación: 80% de reembolso.
-- 5 días o menos: 0% de reembolso.
-- Una reserva solo se puede cancelar una vez.
-- ---------------------------------------------------------------------
CREATE TABLE cancelacion (
  id_cancelacion       NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_reserva           NUMBER(10)          NOT NULL,
  fecha_cancelacion    DATE                DEFAULT SYSDATE NOT NULL,
  dias_anticipacion    NUMBER(4)           NOT NULL,
  porcentaje_reembolso NUMBER(3)           NOT NULL,
  monto_reembolso      NUMBER(12,2)        NOT NULL,
  motivo               VARCHAR2(300 CHAR),
  CONSTRAINT pk_cancelacion          PRIMARY KEY (id_cancelacion),
  CONSTRAINT fk_cancelacion_reserva  FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
  CONSTRAINT uk_cancelacion_reserva  UNIQUE (id_reserva),
  -- Solo se cancela antes de la llegada.
  CONSTRAINT ck_cancelacion_dias     CHECK (dias_anticipacion >= 0),
  CONSTRAINT ck_cancelacion_monto    CHECK (monto_reembolso >= 0),
  -- RN1 declarativa: el porcentaje depende de la anticipación y sin reembolso el monto es 0.
  CONSTRAINT ck_cancelacion_regla    CHECK (
       (dias_anticipacion >  5 AND porcentaje_reembolso = 80)
    OR (dias_anticipacion <= 5 AND porcentaje_reembolso = 0 AND monto_reembolso = 0)
  )
);

COMMENT ON TABLE  cancelacion                      IS 'Cancelación de una reserva y su reembolso (entidad agregada, RN1).';
COMMENT ON COLUMN cancelacion.dias_anticipacion    IS 'Días entre la fecha de cancelación y el checkin de la reserva.';
COMMENT ON COLUMN cancelacion.porcentaje_reembolso IS '80 si se cancela con más de 5 días de anticipación; 0 en otro caso (exactamente 5 días = 0).';
COMMENT ON COLUMN cancelacion.monto_reembolso      IS 'Valor devuelto: porcentaje_reembolso de la suma de pagos EXITOSO.';


