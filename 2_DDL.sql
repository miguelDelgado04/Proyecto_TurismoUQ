

/* =====================================================================
   0. LIMPIEZA: Para borrar las tablass, si esta no existe, se ignora
   el error para que el script sea re-ejecutable.
   ===================================================================== */
DECLARE
  TYPE t_tablas IS TABLE OF VARCHAR2(30);
  v_tablas t_tablas := t_tablas(
    'LIQUIDACION_MENSUAL', 'RESENA', 'RESERVA_SERVICIO', 'CANCELACION',
    'PAGO', 'RESERVA_NOCHE', 'RESERVA_HABITACION', 'RESERVA', 'CLIENTE',
    'AUDITORIA_TARIFA', 'TARIFA', 'TEMPORADA', 'TIPO_TEMPORADA',
    'SERVICIO', 'HABITACION', 'ALOJAMIENTO', 'USUARIO_SISTEMA', 'ROL',
    'TIPO_ALOJAMIENTO', 'MUNICIPIO'
  );
BEGIN
  FOR i IN 1 .. v_tablas.COUNT LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || v_tablas(i) || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
    END;
  END LOOP;
END;
/


/* =====================================================================
   1. CATÁLOGOS Y OFERTA
   ===================================================================== */

-- ---------------------------------------------------------------------
-- MUNICIPIO: los 12 municipios del Quindío.
-- ---------------------------------------------------------------------
CREATE TABLE municipio (
  id_municipio   NUMBER(4)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre         VARCHAR2(60 CHAR)  NOT NULL,
  CONSTRAINT pk_municipio        PRIMARY KEY (id_municipio),
  CONSTRAINT uk_municipio_nombre UNIQUE (nombre)
);

COMMENT ON TABLE  municipio        IS 'Municipios del Quindío donde se ubican los alojamientos.';
COMMENT ON COLUMN municipio.nombre IS 'Nombre oficial del municipio. Único.';


-- ---------------------------------------------------------------------
-- TIPO_ALOJAMIENTO: hotel, finca cafetera, glamping, hostal, cabaña.
-- ---------------------------------------------------------------------
CREATE TABLE tipo_alojamiento (
  id_tipo_alojamiento NUMBER(4)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre              VARCHAR2(40 CHAR)  NOT NULL,
  descripcion         VARCHAR2(200 CHAR),
  CONSTRAINT pk_tipo_alojamiento        PRIMARY KEY (id_tipo_alojamiento),
  CONSTRAINT uk_tipo_alojamiento_nombre UNIQUE (nombre)
);

COMMENT ON TABLE  tipo_alojamiento        IS 'Catálogo ampliable de tipos de alojamiento.';
COMMENT ON COLUMN tipo_alojamiento.nombre IS 'Nombre del tipo (HOTEL, FINCA CAFETERA, GLAMPING, ...). Único.';


-- ---------------------------------------------------------------------
-- ROL: Para cada usuario del sistema.
-- Valores esperados: ADMIN_PLATAFORMA, ENCARGADO_ALOJAMIENTO,
-- RECEPCION, GERENTE, AUDITOR.
-- ---------------------------------------------------------------------
CREATE TABLE rol (
  id_rol         NUMBER(3)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre         VARCHAR2(30 CHAR)  NOT NULL,
  descripcion    VARCHAR2(200 CHAR),
  CONSTRAINT pk_rol           PRIMARY KEY (id_rol),
  CONSTRAINT uk_rol_nombre    UNIQUE (nombre),
  CONSTRAINT ck_rol_nombre_may CHECK (nombre = UPPER(nombre))
);

COMMENT ON TABLE  rol        IS 'Roles funcionales de los usuarios del sistema (entidad agregada).';
COMMENT ON COLUMN rol.nombre IS 'Código del rol en mayúsculas. Único.';


-- ---------------------------------------------------------------------
-- USUARIO_SISTEMA: Para administradores de la plataforma y encargados.
-- usuario_bd vincula a la persona con su usuario de Oracle.
-- ---------------------------------------------------------------------
CREATE TABLE usuario_sistema (
  id_usuario     NUMBER(6)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_rol         NUMBER(3)           NOT NULL,
  usuario_bd     VARCHAR2(128)       NOT NULL,
  nombre         VARCHAR2(100 CHAR)  NOT NULL,
  correo         VARCHAR2(120 CHAR)  NOT NULL,
  activo         CHAR(1)             DEFAULT 'S' NOT NULL,
  fecha_creacion DATE                DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_usuario_sistema         PRIMARY KEY (id_usuario),
  CONSTRAINT fk_usuario_rol             FOREIGN KEY (id_rol) REFERENCES rol (id_rol),
  CONSTRAINT uk_usuario_usuario_bd      UNIQUE (usuario_bd),
  CONSTRAINT uk_usuario_correo          UNIQUE (correo),
  CONSTRAINT ck_usuario_activo          CHECK (activo IN ('S', 'N')),
  -- Oracle guarda los nombres de usuario en mayúsculas (lo que devuelve USER).
  CONSTRAINT ck_usuario_usuario_bd_may  CHECK (usuario_bd = UPPER(usuario_bd)),
  CONSTRAINT ck_usuario_correo          CHECK (REGEXP_LIKE(correo, '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'))
);

COMMENT ON TABLE  usuario_sistema            IS 'Usuarios que administran la plataforma o gestionan alojamientos.';
COMMENT ON COLUMN usuario_sistema.usuario_bd IS 'Usuario de Oracle asociado (en mayúsculas). Se compara con USER en las vistas de seguridad.';
COMMENT ON COLUMN usuario_sistema.activo     IS 'S = puede operar, N = deshabilitado.';


-- ---------------------------------------------------------------------
-- ALOJAMIENTO:
-- id_encargado es obligatorio. Todo alojamiento debe tener un usuario responsable. Un encargado puede gestionar varios alojamientos.
-- ---------------------------------------------------------------------
CREATE TABLE alojamiento (
  id_alojamiento      NUMBER(6)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_municipio        NUMBER(4)           NOT NULL,
  id_tipo_alojamiento NUMBER(4)           NOT NULL,
  id_encargado        NUMBER(6)           NOT NULL,
  nombre_comercial    VARCHAR2(100 CHAR)  NOT NULL,
  direccion           VARCHAR2(150 CHAR)  NOT NULL,
  estrellas           NUMBER(1)           NOT NULL,
  telefono            VARCHAR2(20)        NOT NULL,
  correo              VARCHAR2(120 CHAR)  NOT NULL,
  CONSTRAINT pk_alojamiento            PRIMARY KEY (id_alojamiento),
  CONSTRAINT fk_alojamiento_municipio  FOREIGN KEY (id_municipio)        REFERENCES municipio (id_municipio),
  CONSTRAINT fk_alojamiento_tipo       FOREIGN KEY (id_tipo_alojamiento) REFERENCES tipo_alojamiento (id_tipo_alojamiento),
  CONSTRAINT fk_alojamiento_encargado  FOREIGN KEY (id_encargado)        REFERENCES usuario_sistema (id_usuario),
  -- Dos alojamientos no pueden llamarse igual dentro del mismo municipio.
  CONSTRAINT uk_alojamiento_nombre_mun UNIQUE (id_municipio, nombre_comercial),
  CONSTRAINT ck_alojamiento_estrellas  CHECK (estrellas BETWEEN 1 AND 5),
  CONSTRAINT ck_alojamiento_telefono   CHECK (REGEXP_LIKE(telefono, '^\+?[0-9 ]{7,15}$')),
  CONSTRAINT ck_alojamiento_correo     CHECK (REGEXP_LIKE(correo, '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'))
);

COMMENT ON TABLE  alojamiento              IS 'Establecimientos inscritos en la plataforma.';
COMMENT ON COLUMN alojamiento.id_encargado IS 'Usuario responsable del alojamiento (rol ENCARGADO_ALOJAMIENTO).';
COMMENT ON COLUMN alojamiento.estrellas    IS 'Categoría de 1 a 5 estrellas, autoasignada por el establecimiento.';


-- ---------------------------------------------------------------------
-- HABITACION:
-- El número de habitación es único dentro de su mismo alojamiento.
-- ---------------------------------------------------------------------
CREATE TABLE habitacion (
  id_habitacion   NUMBER(8)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_alojamiento  NUMBER(6)           NOT NULL,
  numero          VARCHAR2(10 CHAR)   NOT NULL,
  capacidad_max   NUMBER(2)           NOT NULL,
  tipo_habitacion VARCHAR2(10)        NOT NULL,
  descripcion     VARCHAR2(300 CHAR),
  CONSTRAINT pk_habitacion             PRIMARY KEY (id_habitacion),
  CONSTRAINT fk_habitacion_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uk_habitacion_aloj_numero UNIQUE (id_alojamiento, numero),
  CONSTRAINT ck_habitacion_capacidad   CHECK (capacidad_max BETWEEN 1 AND 20),
  CONSTRAINT ck_habitacion_tipo        CHECK (tipo_habitacion IN ('SENCILLA', 'DOBLE', 'SUITE', 'CABANA'))
);

COMMENT ON TABLE  habitacion                 IS 'Unidades reservables de cada alojamiento.';
COMMENT ON COLUMN habitacion.numero          IS 'Identificador visible de la habitación. Único dentro del alojamiento.';
COMMENT ON COLUMN habitacion.capacidad_max   IS 'Máximo de huéspedes. RN6: ninguna línea de reserva puede superarlo.';
COMMENT ON COLUMN habitacion.tipo_habitacion IS 'SENCILLA, DOBLE, SUITE o CABANA.';


-- ---------------------------------------------------------------------
-- SERVICIO: servicios adicionales propios de cada alojamiento.
-- ---------------------------------------------------------------------
CREATE TABLE servicio (
  id_servicio    NUMBER(6)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_alojamiento NUMBER(6)           NOT NULL,
  nombre         VARCHAR2(80 CHAR)   NOT NULL,
  descripcion    VARCHAR2(300 CHAR),
  precio         NUMBER(12,2)        NOT NULL,
  CONSTRAINT pk_servicio             PRIMARY KEY (id_servicio),
  CONSTRAINT fk_servicio_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT uk_servicio_aloj_nombre UNIQUE (id_alojamiento, nombre),
  CONSTRAINT ck_servicio_precio      CHECK (precio >= 0)
);

COMMENT ON TABLE  servicio        IS 'Servicios adicionales (tour, transporte, desayuno, ...) que ofrece un alojamiento.';
COMMENT ON COLUMN servicio.precio IS 'Precio vigente en pesos colombianos. Al reservar se copia a RESERVA_SERVICIO (RN9).';


/* =====================================================================
   2. TEMPORADAS Y TARIFAS
